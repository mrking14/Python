a  = {1, 2, 3}
b = {3, 4, 5}

# Union
aUnionB = a.union(b)

#Intersection
aInterSectionB = a.intersection(b)

# Difference (a - b)
aDifferenceB = a.difference(b)

print(f"Union of A and B is :{aUnionB}")
print(f"Intersection of A and B is :{aInterSectionB}")
print(f"Difference of A and B is : {aDifferenceB}")